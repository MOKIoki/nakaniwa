export function getNoteBySlug(slug: string): Note | undefined {
  return notes.find((n) => n.slug === slug);
}

export function getLatestNotes(count: number): Note[] {
  return [...notes]
    .sort((a, b) => (a.date < b.date ? 1 : -1))
    .slice(0, count);
}